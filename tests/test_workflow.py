class Api:
    def __init__(self): self.calls=[]
    def pages(self, endpoint):
        self.calls.append(endpoint)
        if '/pulls?' in endpoint:
            return [dict(number=1, title='Old PR', created_at='2020-01-01T00:00:00Z', updated_at='2026-10-24T00:00:00Z')]
        if endpoint.endswith('/reviews'):
            return [dict(id=7, body='Check error handling', submitted_at='2026-10-24T00:00:00Z', user={'login':'same'}, html_url='review')]
        if endpoint.endswith('/comments'):
            c=dict(id=1, body='Review', created_at='2026-10-24T00:00:00Z', user={'login':'same'}, html_url='inline', path='a.py', diff_hunk='@@', pull_request_review_id=7)
            return [c,c,dict(c,id=2,created_at='2020-01-01T00:00:00Z')]
        raise AssertionError(endpoint)

def test_old_pr_recent_comments_and_dedup():
    result=collect('o/r',30,api=Api(),now=NOW)
    assert len(result['comments']) == 2
    assert result['pr_count'] == 1
    assert result['comments'][0]['pr_title'] == 'Old PR'
    assert result['comments'][0]['diff_context'] == '@@'

