def test_daily_repeat_does_not_bump_revision(tmp_path):
    from hrl.cli import build
    from hrl.io import write_json,read_json
    c=comment(); human=[dict(c,classification='HUMAN')]
    rules=merge([], [obs()],human)
    old=make_record('o/r',render('o/r',rules,'2026-10-24'),rules,None,{})
    write_json(tmp_path/'existing.json',old)
    write_json(tmp_path/'reviews.json',{'repo_id':'o/r','comments':[c]})
    write_json(tmp_path/'classifications.json',[dict(classify(c,{}),classification='HUMAN')])
    write_json(tmp_path/'observations.json',[obs(merge_into='HRL-001')])
    build('o/r',tmp_path)
    assert read_json(tmp_path/'pending.json')['record']==old


