def fake_client(provider="aws"):
    client = create_autospec(BucketClient, instance=True)
    blobs = {}
    client.provider = provider
    client.bucket = "demo-s3" if provider == "aws" else "demo-gcs"
    client.does_bucket_exist.return_value = True
    def upload(key, payload, **kwargs):
        blobs[key] = bytes(payload)
    def download(key):
        if key not in blobs:
            raise ResourceNotFoundException('Object missing')
        return DownloadResponse(key=key, content=blobs[key], metadata=None)
    client.upload.side_effect = upload
    client.download.side_effect = download
    return client, blobs

@pytest.mark.parametrize('provider', ['aws', 'gcp'])
def test_sdk_read_write_and_missing(provider):
    import json
    from hrl.multicloud_store import object_key
    client, blobs = fake_client(provider)
    store = Store(client)
    assert store.load('o/r') is None
    record = make_record('o/r', 'knowledge', [], None, {})
    store.save(record)
    assert store.load('o/r') == record
    assert json.loads(blobs[object_key('o/r')]) == record
    assert client.upload.call_args.kwargs['content_type'] == 'application/json'


