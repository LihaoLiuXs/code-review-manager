def comment(body='Verify idempotency before retrying.', id='inline:1'):
    return dict(comment_id=id, repo_id='o/r', body=body, author_login='same',
                comment_url='https://github.com/o/r/pull/1#discussion_r1', pr_number=1,
                pr_url='https://github.com/o/r/pull/1', file_path='a.py', review_id='7')

def test_classification_conservative_and_same_account():
    assert classify(comment('Generated by Claude Code'), {})['classification'] == 'AI'
    assert classify(comment('LGTM'), {})['classification'] == 'UNCERTAIN'
