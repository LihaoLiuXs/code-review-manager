    assert classify(c, decisions)['classification'] == 'HUMAN'
    assert classify(comment('Generated by Claude Code', 'inline:2'), decisions)['classification'] == 'AI'
    assert classify(comment('edited'), decisions)['classification'] == 'UNCERTAIN'

