"""Conservative per-comment provenance. Style and usernames are never proof."""
import hashlib
import json
import re

AI_PATTERNS = [r'<!--\s*review-source:\s*ai\s*-->', r'(?im)^\s*(?:\*\*)?generated by (?:Claude Code|Copilot|CodeRabbit)\b']


def fingerprint(comment: dict) -> str:
    # Include context: a changed review batch can invalidate previous provenance.
    content = {k: comment.get(k) for k in ('body', 'diff_context', 'related_review_body')}
    return hashlib.sha256(json.dumps(content, sort_keys=True).encode()).hexdigest()


def key(comment: dict) -> str:
    return f'{comment["repo_id"]}:{comment["comment_id"]}'


def manual_decision(comment: dict, decisions: dict) -> dict | None:
    cached = decisions.get(key(comment))
    if (cached and cached.get('fingerprint') == fingerprint(comment)
            and cached.get('classification_method') == 'manual'
            and cached.get('classification') in ('HUMAN', 'AI', 'UNCERTAIN')):
        return cached
    return None


def classify(comment: dict, decisions: dict, patterns: list[str] | None = None) -> dict:
    cached = manual_decision(comment, decisions)
    if cached:
        return dict(cached)
    if any(re.search(p, comment['body']) for p in (AI_PATTERNS if patterns is None else patterns)):
        label, method, reason = 'AI', 'explicit_marker', 'Explicit AI attribution; check quoted examples if necessary'
    else:
        label, method, reason = 'UNCERTAIN', 'contextual_analysis', 'Insufficient reliable provenance; style and account identity are not proof'
    return dict(comment_id=comment['comment_id'], classification=label,
                classification_method=method, reason=reason, fingerprint=fingerprint(comment))


def confirm(comment: dict, label: str, decisions: dict) -> dict:
    if label not in ('HUMAN', 'AI', 'UNCERTAIN'):
        raise ValueError('Choose HUMAN, AI, or UNCERTAIN')
    result = dict(comment_id=comment['comment_id'], classification=label,
                  classification_method='manual', reason='Confirmed by developer' if label != 'UNCERTAIN' else 'Skipped by developer',
                  fingerprint=fingerprint(comment))
    decisions[key(comment)] = result
    return result


def ask(comment: dict, decisions: dict, *, input_fn=input) -> dict:
    print(f"\n{comment['repo_id']} PR #{comment['pr_number']} review {comment.get('review_id')} {comment.get('file_path')}\n{comment['comment_url']}\n{comment['body']}\nContext: {comment.get('diff_context', '')}\nUNCERTAIN: No reliable authorship provenance.")
    try:
        answer = input_fn('1 Human / 2 AI / 3 Skip [3]: ').strip().lower()
    except EOFError:
        result = classify(comment, decisions)
        result['reason'] = 'No interactive input available; developer confirmation is still pending'
        return result
    return confirm(comment, {'1':'HUMAN','human':'HUMAN','2':'AI','ai':'AI'}.get(answer,'UNCERTAIN'), decisions)
